def test_reimport_changes_nothing(old: Path) -> None:
    _run(old)
    before = _snapshot(old)

    again = _run(old)

    assert not again.user_created
    assert again.new_routes == 0
    assert again.gpx_copied == 0
    assert (again.claimed_routes, again.claimed_ratings, again.claimed_pins) == (0, 0, 0)
    assert again.routes == {"import": 2, "garmin": 2}
    assert _snapshot(old) == before


def test_reimport_applies_toml_changes(old: Path) -> None:
    _run(old)
    uid = _uid(old)
    routes_store.update(_db(old), uid, "route-1", {"name": "Edited in the UI"})
    (old / "data/routes/ski.gpx").write_text(_gpx(45.0, 8.0))
    toml = old / "wishmap.toml"
    toml.write_text(toml.read_text().replace('name = "Ski tour"', 'name = "Ski tour 2"'))

    again = _run(old)

    assert again.gpx_copied == 1
    routes = {r.id: r for r in routes_store.get_all(_db(old), uid)}
    assert routes["route-2"].name == "Ski tour 2"
    # The TOML wins over an edit made since the last import.
    assert routes["route-1"].name == "Chasseral"
    udir = user_dir(old / "data", uid)
    assert (udir / "gpx/import/data/routes/ski.gpx").read_text() == _gpx(45.0, 8.0)


def test_reimport_keeps_routes_added_since(old: Path) -> None:
    _run(old)
    uid = _uid(old)
    some_route = routes_store.get_all(_db(old), uid)[0]
    routes_store.insert(_db(old), uid, some_route.model_copy(update={"id": "web-new"}))
    _run(old)
    assert "web-new" in {r.id for r in routes_store.get_all(_db(old), uid)}



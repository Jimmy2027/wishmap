def _foreign_toml(tmp_path: Path) -> Path:
    """Another person's (empty) install: not the server's config."""
    toml = tmp_path / "alice" / "wishmap.toml"
    toml.parent.mkdir()
    toml.write_text('title = "Alice"\n')
    return toml


def test_cli_foreign_toml_claims_nothing_by_default(
    old: Path,
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
) -> None:
    monkeypatch.setenv("WISHMAP_PASSWORD", PASSWORD)
    main(["import-toml", "--user", "alice", str(_foreign_toml(tmp_path))])

    out = capsys.readouterr().out
    assert "  claimed from before accounts" not in out
    assert "left unclaimed from before accounts: 3 row(s)" in out
    uid = _uid(old, "alice")
    assert routes_store.get_all(_db(old), uid) == []
    assert ratings.get_all(_db(old), uid) == {}
    assert [r.id for r in routes_store.get_all(_db(old), UNCLAIMED_USER_ID)] == ["web-old"]
    assert len(ratings.get_all(_db(old), UNCLAIMED_USER_ID)) == 2

    # The owner's own import still finds everything to claim.
    main(["import-toml", "--user", "hendrik", str(old / "wishmap.toml")])
    assert "claimed from before accounts: 1 route(s), 2 rating(s)" in capsys.readouterr().out



def test_import_creates_the_account_and_imports_everything(old: Path) -> None:
    result = _run(old)

    assert result.user_created
    assert result.username == "hendrik"
    assert result.pins == 1
    assert result.routes == {"import": 2, "garmin": 2}
    assert result.new_routes == 4
    # 4 TOML GPX files + the claimed web route's.
    assert result.gpx_copied == 5
    assert (result.claimed_routes, result.claimed_ratings, result.claimed_pins) == (1, 2, 0)
    assert result.unclaimed_conflicts == 0
    assert result.strava_activities == 1
    assert result.garmin_username == "me@example.com"

    uid = _uid(old)
    assert users.authenticate(_db(old), "hendrik", PASSWORD) is not None
    routes = {r.id: r for r in routes_store.get_all(_db(old), uid)}
    assert set(routes) == ALL_ROUTES
    assert {r.id for r in routes_store.get_all(_db(old), uid, "garmin")} == {
        "garmin-11",
        "garmin-12",
    }
    assert {r.id for r in routes_store.get_all(_db(old), uid, "import")} == {
        "route-1",
        "route-2",
    }
    # Fields round-trip; only `gpx` is rewritten into the user's tree.
    g11 = routes["garmin-11"]
    assert (g11.name, g11.sport, g11.notes, g11.strava_id) == (
        "Morning hike",
        ["hiking"],
        "2026-01-01 | 5.0 km",
        77,
    )
    assert routes["route-1"].tags == ["loop"]
    assert {r.id: r.gpx for r in routes.values()} == {
        "route-1": "gpx/import/data/routes/chasseral.gpx",
        "route-2": "gpx/import/data/routes/ski.gpx",
        "garmin-11": "gpx/garmin/11.gpx",
        "garmin-12": "gpx/garmin/12.gpx",
        "web-old": "gpx/web/web-old.gpx",
    }

    udir = user_dir(old / "data", uid)
    assert (udir / "gpx/garmin/11.gpx").read_text() == _gpx(46.1, 9.1)
    assert (udir / "gpx/import/data/routes/ski.gpx").read_text() == _gpx(46.5, 9.5)
    assert (udir / "gpx/web/web-old.gpx").read_text() == _gpx(47.7, 8.7)

    [pin] = pins_store.get_all(_db(old), uid)
    assert (pin.id, pin.sport, pin.tags) == ("pin-1", ["hiking", "ski_touring"], ["hut"])



@pytest.fixture
def old(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """A single-user install, also serving as the server config (WISHMAP_CONFIG)."""
    root = tmp_path / "old"
    files = {
        "wishmap.toml": WISHMAP_TOML,
        "data/garmin/garmin.toml": GARMIN_TOML,
        "data/garmin/11.gpx": _gpx(46.1, 9.1),
        "data/garmin/12.gpx": _gpx(46.2, 9.2),
        "data/routes/chasseral.gpx": _gpx(47.1, 7.0),
        "data/routes/ski.gpx": _gpx(46.5, 9.5),
        "data/strava/routes/web-old.gpx": _gpx(47.7, 8.7),
    }
    for rel, text in files.items():
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(text)
    for name, ddl in (("wishmap.db", LEGACY_DDL), ("strava/activities.db", STRAVA_DDL)):
        conn = sqlite3.connect(root / "data" / name)
        conn.executescript(ddl)
        conn.close()
    monkeypatch.setenv("WISHMAP_CONFIG", str(root / "wishmap.toml"))
    monkeypatch.delenv("WISHMAP_PASSWORD", raising=False)
    return root


def _db(old: Path) -> Path:
    return old / "data" / "wishmap.db"


def _run(
    old: Path, username: str = "hendrik", password: str = PASSWORD, **kw: Any
) -> ImportResult:
    asked: list[str] = []

    def get_password() -> str:
        asked.append(username)
        return password

    # The fixture's TOML is the server's own config, which the CLI claims for.
    kw.setdefault("claim", True)
    result = import_toml(
        old / "wishmap.toml",
        username,
        db_path=_db(old),
        data_root=old / "data",
        legacy_base=old,
        get_password=get_password,
        **kw,
    )
    assert len(asked) == int(result.user_created)
    return result


def _uid(old: Path, username: str = "hendrik") -> int:
    user = users.get_by_username(_db(old), username)
    assert user is not None
    return user.id


def _snapshot(old: Path) -> dict[str, Any]:
    """Every DB row (bar sessions) and every file under data/users."""
    conn = sqlite3.connect(_db(old))
    try:
        tables = {
            t: sorted(map(tuple, conn.execute(f"SELECT * FROM {t}")))
            for t in ("users", "routes", "pins", "route_ratings", "integrations")
        }
    finally:
        conn.close()
    users_dir = old / "data" / "users"
    tables["files"] = sorted(
        (str(p.relative_to(users_dir)), p.read_bytes())
        for p in users_dir.rglob("*")
        if p.is_file() and p.suffix != ".db"
    )
    return tables



def test_claim_conflicts_keep_the_accounts_own_rows(old: Path) -> None:
    user = users.create_user(_db(old), "hendrik", PASSWORD)
    ratings.upsert(_db(old), user.id, "garmin-11", {"fun": 1})
    routes_store.insert(
        _db(old),
        user.id,
        routes_store.get_all(_db(old), UNCLAIMED_USER_ID)[0].model_copy(
            update={"name": "Mine", "gpx": "gpx/web/mine.gpx"}
        ),
    )

    result = _run(old)

    assert (result.claimed_routes, result.claimed_ratings) == (0, 1)
    # The web route and the garmin-11 rating stay with the unclaimed user.
    assert result.unclaimed_conflicts == 2
    mine = routes_store.get(_db(old), user.id, "web-old")
    assert mine is not None and mine.name == "Mine"
    assert ratings.get_all(_db(old), user.id)["garmin-11"]["fun"] == 1
    assert ratings.get_all(_db(old), user.id)["web-old"]["fun"] == 3
    # The skipped route's GPX was not copied over the account's path.
    assert not (user_dir(old / "data", user.id) / "gpx/web/web-old.gpx").exists()



def test_deleting_a_route_keeps_a_gpx_another_route_shares(old: Path) -> None:
    # Two TOML routes naming one GPX file share its single copy.
    toml = old / "wishmap.toml"
    toml.write_text(
        toml.read_text().replace("data/routes/ski.gpx", "data/routes/chasseral.gpx")
    )
    _run(old)
    shared = user_dir(old / "data", _uid(old)) / "gpx/import/data/routes/chasseral.gpx"

    with TestClient(app) as c:
        c.post("/api/auth/login", json={"username": "hendrik", "password": PASSWORD})
        assert c.delete("/api/routes/route-1").status_code == 204
        assert shared.is_file()
        assert c.delete("/api/routes/route-2").status_code == 204
        assert not shared.exists()



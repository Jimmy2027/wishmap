def test_import_only_reads_the_source_install(old: Path) -> None:
    before = {
        p: p.read_bytes()
        for p in old.rglob("*")
        if p.is_file() and p.suffix not in (".db", ".db-wal", ".db-shm")
    }
    _run(old)
    after = {
        p: p.read_bytes()
        for p in old.rglob("*")
        if p.is_file()
        and p.suffix not in (".db", ".db-wal", ".db-shm")
        and "users" not in p.relative_to(old).parts
    }
    assert after == before



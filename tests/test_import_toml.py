    toml = str(old / "wishmap.toml")
    monkeypatch.delenv("WISHMAP_CONFIG")
    monkeypatch.setattr("sys.stdin", io.StringIO(PASSWORD + "\n"))

    main(["--config", toml, "import-toml", "--user", "hendrik", "--password-stdin", toml])

    out = capsys.readouterr().out
    # The server's own TOML is the one imported: no "import them" advice.
    assert "legacy key" not in caplog.text
    assert "into account 'hendrik' (created)" in out
    assert "routes: 2 garmin, 2 import (4 new)" in out
    assert "claimed from before accounts: 1 route(s), 2 rating(s), 0 pin(s)" in out
    assert "Strava activities: 1" in out
    assert users.authenticate(_db(old), "hendrik", PASSWORD) is not None

    # A second run needs no password (stdin is now empty).
    main(["import-toml", "--config", toml, "--user", "hendrik", toml])
    assert "(created)" not in capsys.readouterr().out

    main(["--config", toml, "export", "--user", "hendrik", str(tmp_path / "site")])
    assert "wrote" in capsys.readouterr().out
    assert (tmp_path / "site" / "api" / "routes.json").is_file()


